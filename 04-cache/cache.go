// Package cache: in-memory кэш строк с TTL.
//
// Set кладёт значение на время ttl, Get отдаёт его, пока оно не протухло.
// Len показывает, сколько записей реально лежит в памяти, Close
// останавливает то, что кэш запустил в фоне.
//
// Требования:
//   - Get и Set вызываются из разных горутин одновременно;
//   - Get не отдаёт протухшее значение;
//   - Len возвращает len внутренней map, без фильтрации протухших записей;
//   - протухшие записи удаляются из хранилища сами, без обращений к кэшу,
//     иначе память растёт бесконечно: запись должна исчезнуть не позже чем
//     через секунду после того, как истёк её TTL;
//   - New запускает фоновую чистку, Close её останавливает.
//
// Пример:
//
//	c := New()
//	defer c.Close()
//
//	c.Set("k", "v", 100*time.Millisecond)
//	c.Get("k") // "v", true
//
//	time.Sleep(200 * time.Millisecond)
//	c.Get("k") // "", false
//	c.Len()    // 0, запись вычищена из памяти
