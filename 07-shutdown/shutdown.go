// Package shutdown: корректная остановка приложения.
//
// Run поднимает HTTP-сервер на уже открытом сокете, запускает фоновый воркер
// и блокируется, пока не отменят ctx. После отмены приложение надо остановить
// так, чтобы клиенты не получили обрывов.
//
// Требования:
//   - Run возвращается после отмены ctx или если сервер перестал работать сам;
//   - запросы, которые сервер уже принял, дорабатывают и получают ответ;
//   - новые запросы после остановки не принимаются;
//   - на остановку сервера даётся не больше ShutdownTimeout, если не уложились,
//     наружу уходит ошибка;
//   - http.ErrServerClosed это штатное завершение, а не ошибка;
//   - воркер получает отмену, и Run не возвращается, пока тот не завершился;
//   - Deps закрываются после сервера и воркера, по порядку;
//   - ошибка при закрытии одного не мешает закрыть остальные, наружу уходит
//     объединение всех ошибок (errors.Join) или nil;
//   - после возврата не остаётся работающих горутин.
//
// Пример:
//
//	ln, _ := net.Listen("tcp", "127.0.0.1:8080")
//
//	err := Run(ctx, App{
//		Server:          &http.Server{Handler: mux},
//		Listener:        ln,
//		Worker:          pollQueue,
//		Deps:            []Closer{database},
//		ShutdownTimeout: 5 * time.Second,
//	})
package shutdown

import (
	"context"
	"net"
	"net/http"
	"time"
)

// Closer - ресурс, который надо закрыть при остановке.
type Closer interface {
	Close() error
}

// App - запущенное приложение.
type App struct {
	// Server обслуживает запросы на Listener.
	Server   *http.Server
	Listener net.Listener

	// Worker крутится в фоне и завершается, когда отменят его контекст.
	Worker func(ctx context.Context)

	// Deps закрываются после того, как остановились сервер и воркер.
	Deps []Closer

	// ShutdownTimeout ограничивает время остановки сервера.
	ShutdownTimeout time.Duration
}

// Run запускает приложение и блокируется, пока не отменят ctx.
func Run(ctx context.Context, app App) error {
	panic("не реализовано")
}
